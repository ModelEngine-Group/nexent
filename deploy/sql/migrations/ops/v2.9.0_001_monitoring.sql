CREATE TABLE IF NOT EXISTS ops.ops_monitoring_ingest_batch_t (
    batch_id UUID PRIMARY KEY,
    tenant_id VARCHAR(100) NOT NULL,
    fact_kind VARCHAR(30) NOT NULL,
    write_version BIGINT GENERATED BY DEFAULT AS IDENTITY,
    batch_state VARCHAR(30) NOT NULL DEFAULT 'queued',
    affected_dates DATE[] NOT NULL DEFAULT '{}',
    replay_payload JSONB,
    confirmed_at TIMESTAMPTZ,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    last_error_code VARCHAR(50),
    created_by VARCHAR(100) NOT NULL DEFAULT 'ops-monitoring',
    create_time TIMESTAMP NOT NULL DEFAULT timezone('UTC', now()),
    updated_by VARCHAR(100) NOT NULL DEFAULT 'ops-monitoring',
    update_time TIMESTAMP NOT NULL DEFAULT timezone('UTC', now()),
    delete_flag VARCHAR(1) NOT NULL DEFAULT 'N'
);

COMMENT ON TABLE ops.ops_monitoring_ingest_batch_t IS 'Replayable batches for monitoring fact ingestion';
COMMENT ON COLUMN ops.ops_monitoring_ingest_batch_t.batch_id IS 'Stable identifier for the write batch';
COMMENT ON COLUMN ops.ops_monitoring_ingest_batch_t.tenant_id IS 'Tenant that owns all facts in the batch';
COMMENT ON COLUMN ops.ops_monitoring_ingest_batch_t.fact_kind IS 'Monitoring fact type for all facts in the batch';
COMMENT ON COLUMN ops.ops_monitoring_ingest_batch_t.write_version IS 'Monotonic external write version allocated when staging the batch';
COMMENT ON COLUMN ops.ops_monitoring_ingest_batch_t.batch_state IS 'Queued events, pending replay payload, or confirmed batch';
COMMENT ON COLUMN ops.ops_monitoring_ingest_batch_t.affected_dates IS 'Business dates affected by the batch';
COMMENT ON COLUMN ops.ops_monitoring_ingest_batch_t.replay_payload IS 'Detached events while queued or fixed Elasticsearch writes while pending';
COMMENT ON COLUMN ops.ops_monitoring_ingest_batch_t.confirmed_at IS 'Time the complete batch became searchable';
COMMENT ON COLUMN ops.ops_monitoring_ingest_batch_t.attempt_count IS 'Number of attempts to apply the batch';
COMMENT ON COLUMN ops.ops_monitoring_ingest_batch_t.last_error_code IS 'Stable category of the last application failure';
COMMENT ON COLUMN ops.ops_monitoring_ingest_batch_t.created_by IS 'Actor that first created the record';
COMMENT ON COLUMN ops.ops_monitoring_ingest_batch_t.create_time IS 'Time the row was created in UTC';
COMMENT ON COLUMN ops.ops_monitoring_ingest_batch_t.updated_by IS 'Actor that last updated the row';
COMMENT ON COLUMN ops.ops_monitoring_ingest_batch_t.update_time IS 'Time the row was last updated in UTC';
COMMENT ON COLUMN ops.ops_monitoring_ingest_batch_t.delete_flag IS 'Whether the control record is soft deleted';

CREATE TABLE IF NOT EXISTS ops.ops_monitoring_day_state_t (
    day_state_id UUID PRIMARY KEY,
    tenant_id VARCHAR(100) NOT NULL,
    fact_kind VARCHAR(30) NOT NULL,
    statistic_date DATE NOT NULL,
    source_revision BIGINT NOT NULL DEFAULT 0,
    published_source_revision BIGINT,
    publish_id UUID,
    source_snapshot_at TIMESTAMPTZ,
    published_at TIMESTAMPTZ,
    available_from_at TIMESTAMPTZ,
    last_error_code VARCHAR(50),
    created_by VARCHAR(100) NOT NULL DEFAULT 'ops-monitoring',
    create_time TIMESTAMP NOT NULL DEFAULT timezone('UTC', now()),
    updated_by VARCHAR(100) NOT NULL DEFAULT 'ops-monitoring',
    update_time TIMESTAMP NOT NULL DEFAULT timezone('UTC', now()),
    delete_flag VARCHAR(1) NOT NULL DEFAULT 'N'
);

COMMENT ON TABLE ops.ops_monitoring_day_state_t IS 'Confirmed source and visible publication state per tenant, date and fact type';
COMMENT ON COLUMN ops.ops_monitoring_day_state_t.day_state_id IS 'Stable identifier derived from tenant, fact type and date';
COMMENT ON COLUMN ops.ops_monitoring_day_state_t.tenant_id IS 'Tenant that owns the statistics';
COMMENT ON COLUMN ops.ops_monitoring_day_state_t.fact_kind IS 'Monitoring fact type published on this date';
COMMENT ON COLUMN ops.ops_monitoring_day_state_t.statistic_date IS 'Business date in the configured monitoring timezone';
COMMENT ON COLUMN ops.ops_monitoring_day_state_t.source_revision IS 'Newest confirmed source batch revision for this date';
COMMENT ON COLUMN ops.ops_monitoring_day_state_t.published_source_revision IS 'Source revision captured by the currently readable result';
COMMENT ON COLUMN ops.ops_monitoring_day_state_t.publish_id IS 'Identifier of the currently readable Elasticsearch result';
COMMENT ON COLUMN ops.ops_monitoring_day_state_t.source_snapshot_at IS 'Time at which the published result acquired its source snapshot';
COMMENT ON COLUMN ops.ops_monitoring_day_state_t.published_at IS 'Time the current result became readable';
COMMENT ON COLUMN ops.ops_monitoring_day_state_t.available_from_at IS 'Start of known monitoring coverage for this fact type';
COMMENT ON COLUMN ops.ops_monitoring_day_state_t.last_error_code IS 'Stable category of the most recent aggregation failure';
COMMENT ON COLUMN ops.ops_monitoring_day_state_t.created_by IS 'Actor that first created the record';
COMMENT ON COLUMN ops.ops_monitoring_day_state_t.create_time IS 'Time the row was created in UTC';
COMMENT ON COLUMN ops.ops_monitoring_day_state_t.updated_by IS 'Actor that last updated the row';
COMMENT ON COLUMN ops.ops_monitoring_day_state_t.update_time IS 'Time the row was last updated in UTC';
COMMENT ON COLUMN ops.ops_monitoring_day_state_t.delete_flag IS 'Whether the control record is soft deleted';

CREATE INDEX IF NOT EXISTS ix_ops_monitoring_batch_scope
    ON ops.ops_monitoring_ingest_batch_t (tenant_id, fact_kind, batch_state, write_version)
    WHERE delete_flag = 'N';
CREATE INDEX IF NOT EXISTS ix_ops_monitoring_batch_work
    ON ops.ops_monitoring_ingest_batch_t (write_version)
    WHERE batch_state IN ('queued', 'pending') AND delete_flag = 'N';
CREATE INDEX IF NOT EXISTS ix_ops_monitoring_day_scope
    ON ops.ops_monitoring_day_state_t (tenant_id, fact_kind, statistic_date)
    WHERE delete_flag = 'N';
CREATE INDEX IF NOT EXISTS ix_ops_monitoring_day_work
    ON ops.ops_monitoring_day_state_t (statistic_date)
    WHERE (published_source_revision IS NULL OR source_revision > published_source_revision) AND delete_flag = 'N';
COMMIT;
