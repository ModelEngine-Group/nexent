ALTER TABLE nexent.evolution_generation_attempt_t
    ADD COLUMN IF NOT EXISTS metering_revision CHAR(64),
    ADD COLUMN IF NOT EXISTS budget_stopped BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS nexent.evolution_model_charge_t (
    charge_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id VARCHAR(100) NOT NULL,
    attempt_id BIGINT NOT NULL,
    create_time TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    reserved_input BIGINT NOT NULL,
    reserved_output BIGINT NOT NULL,
    reserved_micros BIGINT NOT NULL,
    input_rate BIGINT NOT NULL,
    output_rate BIGINT NOT NULL,
    reported_input BIGINT,
    reported_output BIGINT,
    reported_micros BIGINT
);
CREATE INDEX IF NOT EXISTS idx_evolution_model_charge_tenant_day
    ON nexent.evolution_model_charge_t (tenant_id, create_time);
CREATE INDEX IF NOT EXISTS idx_evolution_model_charge_attempt
    ON nexent.evolution_model_charge_t (attempt_id);
