CREATE TABLE IF NOT EXISTS nexent.evolution_generation_attempt_t (
    attempt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id VARCHAR(100) NOT NULL,
    source_digest VARCHAR(64) NOT NULL,
    model_id BIGINT NOT NULL,
    created_by VARCHAR(100) NOT NULL,
    create_time TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    lease_until TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    CONSTRAINT evolution_generation_completion_order CHECK (completed_at IS NULL OR completed_at >= create_time)
);
CREATE INDEX IF NOT EXISTS idx_evolution_generation_usage
    ON nexent.evolution_generation_attempt_t (tenant_id, create_time);
CREATE INDEX IF NOT EXISTS idx_evolution_generation_active
    ON nexent.evolution_generation_attempt_t (tenant_id, lease_until) WHERE completed_at IS NULL;
