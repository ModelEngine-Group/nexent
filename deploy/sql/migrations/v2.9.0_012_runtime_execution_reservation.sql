CREATE TABLE IF NOT EXISTS nexent.execution_reservation_t (
    execution_id INT4 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id VARCHAR(100),
    user_id VARCHAR(100),
    execution_kind VARCHAR(30) NOT NULL,
    service_role VARCHAR(30) NOT NULL,
    execution_key VARCHAR(64) NOT NULL,
    agent_scope VARCHAR(100),
    owner_instance_id VARCHAR(100) NOT NULL,
    maintenance_epoch VARCHAR(36) NOT NULL,
    status VARCHAR(30) NOT NULL,
    started_at TIMESTAMP,
    finished_at TIMESTAMP,
    error_code VARCHAR(100),
    create_time TIMESTAMP DEFAULT now(),
    update_time TIMESTAMP DEFAULT now(),
    created_by VARCHAR(100),
    updated_by VARCHAR(100),
    delete_flag VARCHAR(1) NOT NULL DEFAULT 'N'
);

COMMENT ON TABLE nexent.execution_reservation_t IS 'Durable execution ownership, quota reservations and completed Runtime maintenance batches';
COMMENT ON COLUMN nexent.execution_reservation_t.execution_id IS 'Technical identifier and internal generation of this execution';
COMMENT ON COLUMN nexent.execution_reservation_t.tenant_id IS 'Tenant that owns the business execution; null for tenant-neutral maintenance';
COMMENT ON COLUMN nexent.execution_reservation_t.user_id IS 'User on whose behalf the execution runs, if applicable';
COMMENT ON COLUMN nexent.execution_reservation_t.execution_kind IS 'Execution category used for admission and maintenance';
COMMENT ON COLUMN nexent.execution_reservation_t.service_role IS 'Product service that owns execution of this record';
COMMENT ON COLUMN nexent.execution_reservation_t.execution_key IS 'Bounded, server-generated mutual exclusion key for the execution';
COMMENT ON COLUMN nexent.execution_reservation_t.agent_scope IS 'Agent quota scope within the tenant, if applicable';
COMMENT ON COLUMN nexent.execution_reservation_t.owner_instance_id IS 'Instance name and process UUID of the execution owner';
COMMENT ON COLUMN nexent.execution_reservation_t.maintenance_epoch IS 'Identifier of the maintenance batch associated with this execution';
COMMENT ON COLUMN nexent.execution_reservation_t.status IS 'Current execution lifecycle state, used for admission and fencing';
COMMENT ON COLUMN nexent.execution_reservation_t.started_at IS 'UTC time at which the execution started, if it started';
COMMENT ON COLUMN nexent.execution_reservation_t.finished_at IS 'UTC terminal time or maintenance recovery cutoff';
COMMENT ON COLUMN nexent.execution_reservation_t.error_code IS 'Bounded machine-readable terminal error, without request data';
COMMENT ON COLUMN nexent.execution_reservation_t.create_time IS 'Creation time';
COMMENT ON COLUMN nexent.execution_reservation_t.update_time IS 'Last update time';
COMMENT ON COLUMN nexent.execution_reservation_t.created_by IS 'User or system actor that created the record';
COMMENT ON COLUMN nexent.execution_reservation_t.updated_by IS 'User or system actor that last updated the record';
COMMENT ON COLUMN nexent.execution_reservation_t.delete_flag IS 'Soft deletion marker: N for present or Y for deleted';

CREATE INDEX IF NOT EXISTS idx_execution_reservation_active_key
    ON nexent.execution_reservation_t (tenant_id, execution_key)
    WHERE delete_flag = 'N' AND status IN ('PREPARING', 'RUNNING', 'FINALIZING');

CREATE INDEX IF NOT EXISTS idx_execution_reservation_active_agent
    ON nexent.execution_reservation_t (tenant_id, agent_scope)
    WHERE delete_flag = 'N' AND execution_kind = 'agent' AND status IN ('PREPARING', 'RUNNING', 'FINALIZING');

CREATE INDEX IF NOT EXISTS idx_execution_reservation_agent_owner
    ON nexent.execution_reservation_t (tenant_id, user_id, execution_key, execution_id DESC)
    WHERE delete_flag = 'N' AND execution_kind = 'agent' AND service_role = 'runtime';

CREATE INDEX IF NOT EXISTS idx_execution_reservation_maintenance
    ON nexent.execution_reservation_t (maintenance_epoch, execution_kind, status)
    WHERE delete_flag = 'N';
